let current = localStorage.getItem("app_lang") || "en";

export async function changeLanguage(lang) {
  if (translations[lang]) {
    current = lang;
    localStorage.setItem("app_lang", lang);
    window.dispatchEvent(new CustomEvent("app_language_changed", { detail: lang }));
    window.dispatchEvent(new CustomEvent("app_lang_changed_for_voice", { detail: lang }));
    return true;
  }
  return false;
}

export function t(key) {
  const bucket = translations[current] || translations["en"];
  return bucket[key] || key;
}

export function getLanguage() {
  return current;
}

const i18n = { changeLanguage, t, getLanguage, translations };
export default i18n;
